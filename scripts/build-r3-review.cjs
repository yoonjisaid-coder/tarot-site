// Builds docs/quality/R3_REVIEW.md: 20 full Korean readings for human editorial review.
// Usage: node scripts/build-r3-review.cjs <compiled lib dir>
// Shows exactly what the result screen renders from the reading engine. The clarity and message cards
// (separate random decks shown after the spread) are not part of the interpretation engine and are omitted.
const path=require('node:path');const fs=require('node:fs');
const root=process.argv[2];if(!root)throw Error('Provide the compiled lib dir');
const {koCards}=require(path.join(root,'tarot-ko.js'));
const S=require(path.join(root,'reading-scenarios.js'));
const T=require(path.join(root,'timing.js'));
const set=require('./quality-fixtures-r3.cjs');
let md='# R3 human review set\n\nGenerated by `scripts/build-r3-review.cjs` from the current engine. 20 Korean readings, shown as the result screen renders them (answer heading with verdict label, each card\'s four sections, the combined reading and the next step). Not self-scored; for human editorial review.\n';
const misses=[];
for(const f of set){
 const q=S.getScenario(f.q,true);const ds=f.cards.slice(0,q.count).map(([c,r])=>({card:koCards[c],reversed:r}));
 const label=S.readingLabel(ds,q,true);if(f.expect&&label!==f.expect)misses.push(`#${f.id} expected ${f.expect}, got ${label}`);
 const sum=S.readingSummary(ds,q,true);
 md+=`\n---\n\n## ${f.id}. ${f.group}\n\n**QUESTION** ${f.text}  \n(UNTOLD question: ${q.title})\n\n**CARDS** ${ds.map((d,i)=>`${q.positions[i]} — ${d.card.name}${d.reversed?' (역방향)':''}`).join(' / ')}\n\n**ANSWER**${label?` · ${label}`:''}\n\n${sum.answer}\n\n**FULL RESULT**\n`;
 ds.forEach((d,i)=>{md+=`\n${i+1}. ${q.positions[i]} · ${d.card.name}${d.reversed?' (역방향)':''}\n`;for(const s of S.detailedReading(d,q,i,true,ds))md+=`   - ${s.title}: ${s.text}\n`});
 md+=`\n카드를 함께 읽으면\n\n- ${sum.lead}\n${sum.body?`- ${sum.body}\n`:''}- 지금 해볼 일: ${sum.action}\n`;
 if(T.isTiming(q.id))md+=`\n(timing question: the result screen also shows "${T.timingReading(ds[0],q.id,true).speed} · ${T.timingReading(ds[0],q.id,true).window}")\n`;
}
if(misses.length)throw Error('Set no longer covers the required verdicts: '+misses.join('; '));
fs.writeFileSync('docs/quality/R3_REVIEW.md',md);console.log('wrote docs/quality/R3_REVIEW.md',md.length,'chars');
